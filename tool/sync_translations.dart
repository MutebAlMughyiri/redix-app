import 'dart:convert';
import 'dart:io';

/// Writes `lib/words/word_getters.g.dart`: one typed getter per word key in the REDIX database, read through a running API.
/// Only the keys reach the code; the values stay in the database.
/// Run from the repo root: `dart run tool/sync_translations.dart [api base url]`
Future<void> main(List<String> arguments) async {
  final baseUrl = arguments.isEmpty ? 'http://localhost:5010' : arguments.first;
  final client = HttpClient();
  final keys = <String>{};
  for (final language in ['ar', 'en']) {
    final response = await (await client.getUrl(Uri.parse('$baseUrl/translations/$language'))).close();
    final body = await response.transform(utf8.decoder).join();
    if (response.statusCode != HttpStatus.ok) {
      throw StateError('GET /translations/$language answered ${response.statusCode}');
    }
    keys.addAll((jsonDecode(body) as Map).keys.cast<String>());
  }
  client.close();

  final getters = (keys.toList()..sort()).map((key) => "  /// The word `$key`.\n  String get ${getterName(key)} => text('$key');").join('\n\n');
  File('lib/words/word_getters.g.dart').writeAsStringSync('''
// Copyright 2026 Tech Details. All rights reserved.
// Use of this file is governed by the LICENSE file at the root of this repository.

// Generated by tool/sync_translations.dart from the REDIX database. Do not edit.

/// One typed getter per word key in the database.
mixin WordGetters {
  /// The word for [key] in the language in use.
  String text(String key);

$getters
}
''');
}

String getterName(String key) {
  final parts = key.split('.');
  return parts.first + parts.skip(1).map((part) => part[0].toUpperCase() + part.substring(1)).join();
}
